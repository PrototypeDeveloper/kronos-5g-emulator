func testSchema(t testing.TB) (aper.Schema, *aper.Codec) {
	t.Helper()
	s := ngapcodec.NewSchema()
	c, e := aper.NewCodec(s, aper.DefaultLimits())
	if e != nil {
		t.Fatal(e)
	}
	return s, c
}
func TestAllSignals(t *testing.T) {
	s, _ := testSchema(t)
	for _, example := range messageExamples {
		v := reflect.ValueOf(example).Elem()
		name := v.Type().Name()
		t.Run(name, func(t *testing.T) {
			populate(t, s, s.Types[s.Names[name]], v, 0)
			b, e := ngap.Encode(v.Addr().Interface())
			if e != nil {
				t.Fatal(e)
			}
			decoded, e := ngap.Decode(b)
			if e != nil {
				t.Fatal(e)
			}
			if reflect.TypeOf(decoded) != v.Addr().Type() {
				t.Fatalf("wrong signal %T", decoded)
			}
			again, e := ngap.Encode(decoded)
			if e != nil || !bytes.Equal(b, again) {
				t.Fatalf("signal round trip %v", e)
			}
		})
	}
}
func TestAllParameters(t *testing.T) {
	s, c := testSchema(t)
	for _, example := range parameterExamples {
		v := reflect.ValueOf(example).Elem()
		name := v.Type().Name()
		t.Run(name, func(t *testing.T) {
			populate(t, s, s.Types[s.Names[name]], v, 0)
			b, e := v.Addr().Interface().(interface{ Encode() ([]byte, error) }).Encode()
			if e != nil {
				t.Fatal(e)
			}
			dst := reflect.New(v.Type())
			if e = c.Unmarshal(name, b, dst.Interface()); e != nil {
				t.Fatal(e)
			}
			again, e := c.Marshal(name, dst.Interface())
			if e != nil || !bytes.Equal(b, again) {
				t.Fatalf("parameter round trip %v", e)
			}
		})
	}
}
func populate(t testing.TB, s aper.Schema, d *aper.Type, v reflect.Value, depth int) {
	t.Helper()
	if d == nil || depth > 80 {
		t.Fatal("test schema recursion")
	}
	if d.Kind == "REFERENCE" {
		populate(t, s, s.Types[d.Ref], v, depth+1)
		return
	}
	p := v
	if p.Kind() == reflect.Struct {
		if f := p.FieldByName("Value"); f.IsValid() {
			p = f
		}
	}
	size := 0
	for _, c := range d.Constraints {
		if c.Kind == "size" {
			size, _ = strconv.Atoi(c.Lower)
		}
	}
	switch d.Kind {
	case "INTEGER":
		n := big.NewInt(0)
		for _, c := range d.Constraints {
			if c.Kind == "value" {
				n, _ = new(big.Int).SetString(c.Lower, 10)
			}
		}
		if p.Kind() == reflect.Uint64 {
			p.SetUint(n.Uint64())
		} else {
			p.SetInt(n.Int64())
		}
	case "ENUMERATED":
		p.SetUint(uint64(d.Values[0].Number))
	case "BOOLEAN", "NULL":
	case "OCTET STRING":
		p.SetBytes(make([]byte, size))
	case "BIT STRING":
		p.FieldByName("Bytes").SetBytes(make([]byte, (size+7)/8))
		p.FieldByName("BitLength").SetUint(uint64(size))
	case "PrintableString", "VisibleString", "UTF8String":
		p.SetString(string(bytes.Repeat([]byte{'A'}, size)))
	case "OBJECT IDENTIFIER":
		p.Set(reflect.ValueOf([]uint64{1, 2, 840, 113549}))
	case "SEQUENCE":
		for _, f := range d.Fields {
			if f.Optional || f.Default != "" || f.Extension {
				continue
			}
			populate(t, s, f.Type, v.FieldByName(f.GoField), depth+1)
		}
	case "CHOICE":
		v.FieldByName("Present").SetUint(1)
		f := d.Fields[0]
		populate(t, s, f.Type, v.FieldByName(f.GoField), depth+1)
	case "SEQUENCE OF", "CONTAINER":
		if v.Kind() == reflect.Struct {
			v = v.FieldByName("List")
		}
		var mandatory []int
		if d.Kind == "CONTAINER" {
			for i, ie := range s.Sets[d.Ref].IEs {
				if ie.Presence == "mandatory" {
					mandatory = append(mandatory, i)
				}
			}
			if len(mandatory) > size {
				size = len(mandatory)
			}
		}
		v.Set(reflect.MakeSlice(v.Type(), size, size))
		elem := d.Element
		if d.Kind == "CONTAINER" {
			elem = &aper.Type{Kind: "ENTRY", Ref: d.Ref}
		}
		for i := 0; i < size; i++ {
			if i < len(mandatory) {
				fillEntry(t, s, s.Sets[d.Ref], mandatory[i], v.Index(i), depth+1)
			} else {
				populate(t, s, elem, v.Index(i), depth+1)
			}
		}
	case "ENTRY":
		set := s.Sets[d.Ref]
		if len(set.IEs) > 0 {
			v.FieldByName("Present").SetUint(1)
			ie := set.IEs[0]
			v.FieldByName("ID").FieldByName("Value").SetInt(ie.ID)
			cr := uint64(0)
			if ie.Criticality == "ignore" {
				cr = 1
			}
			if ie.Criticality == "notify" {
				cr = 2
			}
			v.FieldByName("Criticality").FieldByName("Value").SetUint(cr)
			populate(t, s, ie.Type, v.FieldByName(ie.GoField), depth+1)
		} else {
			v.FieldByName("Present").SetUint(1)
			v.FieldByName("Criticality").FieldByName("Value").SetUint(1)
			v.FieldByName("UnknownValue").SetBytes([]byte{0})
			if set.Class == "NGAP-PRIVATE-IES" {
				id := v.FieldByName("ID")
				id.FieldByName("Present").SetUint(1)
				id.FieldByName("Local").SetInt(1)
			} else {
				v.FieldByName("ID").FieldByName("Value").SetInt(65000)
			}
		}
	case "MESSAGE":
		set := s.Sets[d.Ref]
		if set.Class == "NGAP-PRIVATE-IES" {
			list := v.FieldByName("PrivateIEs")
			list.Set(reflect.MakeSlice(list.Type(), 1, 1))
			populate(t, s, &aper.Type{Kind: "ENTRY", Ref: d.Ref}, list.Index(0), depth+1)
		} else {
			for _, ie := range set.IEs {
				if ie.Presence == "mandatory" {
					populate(t, s, ie.Type, v.FieldByName(ie.GoField), depth+1)
				}
			}
		}
	default:
		t.Fatalf("test unsupported %s", d.Kind)
	}
}

func fillEntry(t testing.TB, s aper.Schema, set aper.ObjectSet, index int, v reflect.Value, depth int) {
	ie := set.IEs[index]
	v.FieldByName("Present").SetUint(uint64(index + 1))
	v.FieldByName("ID").FieldByName("Value").SetInt(ie.ID)
	cr := uint64(0)
	if ie.Criticality == "ignore" {
		cr = 1
	}
	if ie.Criticality == "notify" {
		cr = 2
	}
	v.FieldByName("Criticality").FieldByName("Value").SetUint(cr)
	populate(t, s, ie.Type, v.FieldByName(ie.GoField), depth+1)
}

func TestParameterAlternatives(t *testing.T) {
	s, c := testSchema(t)
	for _, example := range parameterExamples {
		typ := reflect.TypeOf(example).Elem()
		name := typ.Name()
		d := s.Types[s.Names[name]]
		count := 0
		switch d.Kind {
		case "CHOICE", "SEQUENCE":
			count = len(d.Fields)
		case "ENUMERATED":
			count = len(d.Values)
		case "ENTRY":
			count = len(s.Sets[d.Ref].IEs)
		}
		for index := 0; index < count; index++ {
			t.Run(name+"/"+strconv.Itoa(index), func(t *testing.T) {
				v := reflect.New(typ).Elem()
				populate(t, s, d, v, 0)
				switch d.Kind {
				case "ENUMERATED":
					v.FieldByName("Value").SetUint(uint64(d.Values[index].Number))
				case "CHOICE":
					f := d.Fields[index]
					v.FieldByName("Present").SetUint(uint64(index + 1))
					populate(t, s, f.Type, v.FieldByName(f.GoField), 0)
				case "SEQUENCE":
					f := d.Fields[index]
					if !f.Optional && !f.Extension {
						t.Skip("covered mandatory field")
					}
					v.FieldByName("Has" + f.GoField).SetBool(true)
					populate(t, s, f.Type, v.FieldByName(f.GoField), 0)
				case "ENTRY":
					fillEntry(t, s, s.Sets[d.Ref], index, v, 0)
				}
				b, e := c.Marshal(name, v.Interface())
				if e != nil {
					t.Fatal(e)
				}
				dst := reflect.New(typ)
				if e = c.Unmarshal(name, b, dst.Interface()); e != nil {
					t.Fatal(e)
				}
				again, e := c.Marshal(name, dst.Interface())
				if e != nil || !bytes.Equal(b, again) {
					t.Fatalf("variant round trip: %v", e)
				}
			})
		}
	}
}
